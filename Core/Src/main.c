void HAL_UARTEx_RxEventCallback(UART_HandleTypeDef *huart, uint16_t Size){
	if(huart==&huart2){
		HAL_UART_Transmit_IT(&huart2,(uint8_t*)command,Size);
		if(strncmp(command,"set_mode",8)==0){
			if(strncmp(command,"set_mode on",11)==0){
			light_mode = on;
			}
			else if(strncmp(command,"set_mode off",12)==0){
			light_mode = off;
			}
			else if(strncmp(command,"set_mode blink",14)==0){
				char fre_bl[4]="aaaa";
				for(int i=0;command[i+15]!='\0';i++){
					fre_bl[i]=command[i+15];
				}
				frequency_blink=atof(fre_bl);
				for(int i=0;i<4;i++){
				fre_bl[i]='a';
				}
				light_mode = blink;
			}
			else if(strncmp(command,"set_mode breathe",16)==0){
				char fre[4]="aaaa";
				for(int i=0;command[i+17]!='\0';i++){
					fre[i]=command[i+17];
				}
				frequency_breath=atof(fre);
				for(int i=0;i<4;i++){
				fre[i]='a';
				}
				light_mode = breath;
			}
		}
		else if(strncmp(command,"set_brightness",14)==0){
			char bri[5]="aaaaa";
				for(int i=0;command[i+15]!='\0';i++){
					bri[i]=command[i+15];
				}
				brightness=atof(bri);
				for(int i=0;i<5;i++){
				bri[i]='a';
				}
		}
		HAL_UARTEx_ReceiveToIdle_IT(&huart2,(uint8_t*)command,sizeof(command));
	}
}


