void light_blink(float x){
	while(1){
					__HAL_TIM_SET_COMPARE(&htim3,TIM_CHANNEL_1,99);
					HAL_Delay(500/x-1);
					__HAL_TIM_SET_COMPARE(&htim3,TIM_CHANNEL_1,0);
					HAL_Delay(500/x-1);
		if(light_mode!=blink||x!=frequency_blink) break;
	}
}
void light_breath(float x){
	while(1){
		for(int i=0;i<100;i++){
			__HAL_TIM_SET_COMPARE(&htim3,TIM_CHANNEL_1,i);
			HAL_Delay(5/(2*x)-1);
			}
		for(int i=99;i>=0;i--){
			__HAL_TIM_SET_COMPARE(&htim3,TIM_CHANNEL_1,i);
			HAL_Delay(5/(2*x)-1);
			}
		if(light_mode!=breath||x!=frequency_breath) {
			__HAL_TIM_SET_COMPARE(&htim3,TIM_CHANNEL_1,50);
			break;
		}
	}
}
